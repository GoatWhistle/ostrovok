def add(group: str, query: str, keep: list[str], city: str = "") -> None:
    item: dict[str, object] = {
        "group": group,
        "expect": "any",
        "query": " ".join(query.split()),
        "must_keep": keep,
    }
    if city:
        item["expected_location"] = city
    cases.append(item)


