const fs = require('node:fs')
const assert = require('node:assert/strict')
const { chromium } = require('/home/ikhail_horokhorin/projects/o-hack-sochi/frontend/node_modules/playwright')
const root='/home/ikhail_horokhorin/projects/o-hack-sochi'
const out='/home/ikhail_horokhorin/projects/o-hack-sochi/work/frontend-evolution/evidence/e16-regression/h06'
fs.mkdirSync(out,{recursive:true})
;(async()=>{
const browser=await chromium.launch({headless:true})
const rows=[]
try {
for (const width of [375,1440]) for (const language of ['ru','en']) for (const theme of ['light','dark']) {
  const t=JSON.parse(fs.readFileSync(`${root}/frontend/src/shared/i18n/locales/${language}/explore.json`))
  const page=await browser.newPage({viewport:{width,height:1000},reducedMotion:'reduce'})
  const row={width,language,theme,errors:[],writes:[]};rows.push(row)
  page.setDefaultTimeout(15000)
  page.on('pageerror',e=>row.errors.push(e.message))
  page.on('request',r=>{if(['POST','PATCH'].includes(r.method())) row.writes.push(r.url())})
  await page.addInitScript(({language,theme})=>{localStorage.setItem('app-locale',language);localStorage.setItem('app-theme',theme)},{language,theme})
  await page.goto('http://127.0.0.1:5179/hotelier/h_demo_typed_check')
  const note=page.getByRole('textbox',{name:t.answerFields.note,exact:true})
  await note.fill('Draft in original question')
  const facts=page.getByRole('complementary',{name:t.hotelier.facts,exact:true})
  const height=facts.locator('button[data-fact-trigger]').first()
  const id=await height.getAttribute('data-fact-trigger')
  await height.click()
  const edit=facts.getByRole('button',{name:t.details.wrong,exact:true})
  await edit.click()
  const input=facts.getByRole('textbox',{name:t.details.correction,exact:true})
  const initial=await input.inputValue()
  await input.fill('18')
  await page.keyboard.press('Escape')
  await input.waitFor({state:'hidden'})
  assert.equal(await edit.evaluate(e=>e===document.activeElement),true)
  assert.equal(await facts.getByRole('button',{name:t.hotelier.backToFacts,exact:true}).count(),1)
  await edit.press('Enter')
  assert.equal(await input.inputValue(),'18')
  await facts.getByRole('button',{name:t.details.cancel,exact:true}).click()
  await input.waitFor({state:'hidden'})
  await edit.click()
  assert.equal(await input.inputValue(),initial)
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
  const restored=facts.locator(`[data-fact-trigger="${id}"]`)
  await restored.waitFor()
  assert.equal(await restored.evaluate(e=>e===document.activeElement),true)
  const settings=page.getByRole('button',{name:t.landing.settings,exact:true})
  await settings.click()
  await page.keyboard.press('Escape')
  assert.equal(await settings.evaluate(e=>e===document.activeElement),true)
  assert.equal(await settings.getAttribute('aria-expanded'),'false')
  if(width===375){
    const all=page.getByRole('button',{name:new RegExp(t.hotelier.allQuestions.split(':')[0])})
    await all.click()
    await page.keyboard.press('Escape')
    assert.equal(await all.evaluate(e=>e===document.activeElement),true)
    await all.click()
    const queue=page.getByRole('complementary',{name:t.hotelier.queue,exact:true})
    await queue.locator('li button[aria-current="true"]').press('Enter')
    assert.equal(await page.evaluate(()=>document.activeElement?.matches('p[tabindex="-1"]')),true)
  }
  assert.equal(await note.inputValue(),'Draft in original question')
  const change=page.getByRole('button',{name:t.hotelier.change,exact:true})
  await change.press('Enter'); assert.equal(await change.getAttribute('aria-expanded'),'true')
  await change.press('Space'); assert.equal(await change.getAttribute('aria-expanded'),'false')
  const preview=page.getByRole('button',{name:t.hotelier.preview,exact:true})
  await preview.click()
  await page.getByRole('dialog').waitFor()
  await page.keyboard.press('Escape')
  await page.getByRole('dialog').waitFor({state:'detached'})
  assert.equal(await preview.evaluate(e=>e===document.activeElement),true)
  assert.equal(await note.inputValue(),'Draft in original question')
  assert.equal(row.writes.length,0)
  assert.equal(row.errors.length,0)
  row.passed=true
  await page.screenshot({path:`${out}/${width}-${language}-${theme}.png`,fullPage:true})
  console.log(JSON.stringify(row)); await page.close()
}
}finally{fs.writeFileSync(`${out}/results.json`,JSON.stringify(rows,null,2));await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
