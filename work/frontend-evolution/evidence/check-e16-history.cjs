const fs = require("node:fs")
const { chromium } = require("/home/ikhail_horokhorin/projects/o-hack-sochi/frontend/node_modules/playwright")
const chat = JSON.parse(fs.readFileSync(`${__dirname}/e12-conversation.json`)).id
;(async () => {
  const browser = await chromium.launch({ headless: true, args: ["--disable-webgl"] })
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: "reduce" })
  await page.addInitScript(() => localStorage.setItem("app-locale", "ru"))
  const urls = () => page.url().replace("http://127.0.0.1:5181", "")
  await page.goto(`http://127.0.0.1:5181/?chat=${chat}&tab=hotels`)
  await page.locator("#hotel-result-n11331531334").click()
  console.log("panel", urls(), await page.evaluate(() => history.length))
  await page.getByRole("button", { name: "Карта на весь экран", exact: true }).click()
  await page.locator('[data-full-map="true"]').first().waitFor()
  console.log("full", urls(), await page.evaluate(() => history.length))
  await page.getByRole("button", { name: "Вернуться к поиску", exact: true }).click()
  await page.waitForTimeout(800)
  console.log("exit", urls(), await page.evaluate(() => history.length))
  await page.evaluate(() => history.back()); await page.waitForTimeout(1200)
  console.log("back", urls(), "full map shown:", await page.locator('[data-full-map="true"]').count())
  await page.evaluate(() => history.back()); await page.waitForTimeout(1200)
  console.log("back2", urls())
  await page.evaluate(() => history.forward()); await page.waitForTimeout(1200)
  console.log("fwd", urls())
  await browser.close()
})()
